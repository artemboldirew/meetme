package ru.vsu.cs.boldyrev.shopik.dictionary;

/**
 * Enum, представляющий статусы позиции заказа.
 * <p>
 * Используется для отслеживания жизненного цикла каждого {@link ru.vsu.cs.boldyrev.shopik.entity.OrderItem}.
 * </p>
 */
public enum OrderItemStatus {

    /** Позиция добавлена в заказ и ожидает обработки. */
    PENDING,

    /** Позиция подтверждена для дальнейшей обработки. */
    CONFIRMED,

    /** Позиция готовится к отправке / комплектуется. */
    PREPARING,

    /** Позиция готова и ожидает отгрузки. */
    AWAITING_SHIPMENT,

    /** Позиция отправлена, но ещё не доставлена клиенту. */
    SHIPPED,

    /** Позиция доставлена службой доставки клиенту. */
    DELIVERED,

    /** Клиент получил позицию (подтверждение получения). */
    RECEIVED,

    /** Позиция отменена до отправки или в процессе обработки. */
    CANCELLED,

    /** Позиция возвращена и оплата возвращена клиенту. */
    REFUNDED
}
