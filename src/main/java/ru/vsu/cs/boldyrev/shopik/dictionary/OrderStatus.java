package ru.vsu.cs.boldyrev.shopik.dictionary;

/**
 * Enum, представляющий статусы заказа.
 * <p>
 * Используется для отслеживания жизненного цикла {@link ru.vsu.cs.boldyrev.shopik.entity.Order}.
 * </p>
 */
public enum OrderStatus {

    /** Заказ создан и ожидает подтверждения или обработки. */
    PENDING,

    /** Заказ подтверждён и готов к обработке. */
    CONFIRMED,

    /** Заказ находится в процессе обработки (например, сборка и подготовка к отгрузке). */
    PROCESSING,

    /** Заказ отменён до или во время обработки. */
    CANCELLED,

    /** Заказ полностью выполнен и завершён. */
    COMPLETED
}
