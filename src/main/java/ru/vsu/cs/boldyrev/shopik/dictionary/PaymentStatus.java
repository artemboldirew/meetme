package ru.vsu.cs.boldyrev.shopik.dictionary;

/**
 * Enum, представляющий статусы оплаты заказа.
 * <p>
 * Используется для отслеживания состояния платежа {@link ru.vsu.cs.boldyrev.shopik.entity.Order}.
 * </p>
 */
public enum PaymentStatus {

    /** Платёж создан и ожидает завершения (не оплачен). */
    PENDING,

    /** Платёж успешно выполнен, деньги получены. */
    PAID,

    /** Платёж не прошёл из-за ошибки (например, отказ банка или некорректные данные). */
    FAILED,

    /** Деньги возвращены клиенту после отмены или возврата товара. */
    REFUNDED,

    /** Оплата отменена до списания средств (например, отмена заказа). */
    CANCELLED
}
